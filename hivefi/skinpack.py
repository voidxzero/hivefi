# Hivefi's own skins: only four colours per skin, the rest of the palette is derived from them.
def _rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _hex(c):
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v))) for v in c)


def _mix(a, b, t):
    """t=0 -> a, t=1 -> b"""
    x, y = _rgb(a), _rgb(b)
    return _hex(tuple(p + (q - p) * t for p, q in zip(x, y)))


def _lum(h):
    r, g, b = _rgb(h)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def derive(bg, fg, accent, sel, light=False, lcd=None):
    white, black = "#ffffff", "#000000"
    up, down = (black, white) if light else (white, black)          # "toward the foreground" / "away from it"
    dark = not light
    inset = _mix(bg, white, 0.75) if light else _mix(bg, black, 0.35)
    return {
        "bg": bg, "text": fg, "accent": accent, "sel": sel, "sel_text": white if _lum(sel) < 150 else black,
        "accent_text": black if _lum(accent) > 140 else white,
        "panel_top": _mix(bg, white, 0.10) if dark else _mix(bg, white, 0.55),
        "panel_bot": bg if dark else _mix(bg, black, 0.06),
        "inset": inset, "alt": _mix(inset, bg, 0.45),
        "border": _mix(bg, fg, 0.25), "hilite": _mix(bg, fg, 0.4), "dim": _mix(fg, bg, 0.42),
        "btn_top": _mix(bg, white, 0.16) if dark else _mix(bg, white, 0.7),
        "btn_bot": _mix(bg, white, 0.05) if dark else _mix(bg, black, 0.08),
        "title_top": _mix(bg, white, 0.13) if dark else _mix(bg, white, 0.45),
        "title_bot": _mix(bg, black, 0.12) if dark else _mix(bg, black, 0.1),
        "lcd_bg": lcd or (_mix(bg, black, 0.55) if dark else "#0a1d47"),
        "lcd_fg": accent if dark else "#8fd2ff", "lcd_dim": _mix(_mix(bg, black, 0.5), accent, 0.22),
        "good": "#5cf08c" if dark else "#16834a", "warn": "#f2c230" if dark else "#a8670e",
        "bad": "#ff6b6b" if dark else "#cc2b2b",
    }


